# ---------------------------------------------------------
# CELL 12: VISUALIZATION 1
# AVERAGE YIELD BY SEASON
# ---------------------------------------------------------

# Define the correct seasonal order
season_order = ["Kharif", "Rabi", "Zaid"]

# Calculate average yield for each season
season_yield = (
    df_clean
    .groupby("Season")["Yield_Tonnes_Ha"]
    .mean()
    .reindex(season_order)
)

# Create the bar chart
plt.figure(figsize=(10, 6))

ax = sns.barplot(
    x=season_yield.index,
    y=season_yield.values
)

# Add chart title
plt.title(
    "Average Agricultural Yield by Season",
    fontweight="bold"
)

# Add axis labels
plt.xlabel("Season")
plt.ylabel("Average Yield (Tonnes/Ha)")

# Display values on top of each bar
for i, value in enumerate(season_yield.values):

    ax.text(
        i,
        value + 0.1,
        f"{value:.2f}",
        ha="center",
        fontweight="bold"
    )

# Adjust the layout
plt.tight_layout()

# Display the graph
plt.show()

# ---------------------------------------------------------
# CELL 13: VISUALIZATION 2
# AVERAGE PROFIT BY SEASON
# ---------------------------------------------------------

# Calculate the average profit for each season
season_profit = (
    df_clean
    .groupby("Season")["Profit_INR"]
    .mean()
    .reindex(season_order)
)

# Create the bar chart
plt.figure(figsize=(10, 6))

ax = sns.barplot(
    x=season_profit.index,
    y=season_profit.values
)

# Add title
plt.title(
    "Average Profit by Agricultural Season",
    fontweight="bold"
)

# Add axis labels
plt.xlabel("Season")
plt.ylabel("Average Profit (INR)")

# Display profit values above bars
for i, value in enumerate(season_profit.values):

    # Choose a small offset depending on positive/negative value
    offset = 5000 if value >= 0 else -15000

    ax.text(
        i,
        value + offset,
        f"₹{value:,.0f}",
        ha="center",
        fontweight="bold"
    )

# Keep the actual INR values visible
plt.ticklabel_format(
    style="plain",
    axis="y"
)

# Adjust layout
plt.tight_layout()

# Display graph
plt.show()

# ---------------------------------------------------------
# CELL 14: VISUALIZATION 3
# AVERAGE YIELD BY CROP
# ---------------------------------------------------------

