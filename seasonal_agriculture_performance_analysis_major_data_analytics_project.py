df = pd.read_csv(file_name)

# Display a confirmation message
print("Dataset loaded successfully!")

# Display the name of the file
print("File Name:", file_name)

# ---------------------------------------------------------
# CELL 3: DISPLAY THE DATASET
# ---------------------------------------------------------

# Display the number of rows and columns
print("Dataset Shape:", df.shape)

# Display the first 5 records
print("\nFirst 5 Records:")
display(df.head())

# ---------------------------------------------------------
# CELL 4: DISPLAY LAST 5 RECORDS
# ---------------------------------------------------------

# Display the last 5 rows of the dataset
print("Last 5 Records:")

display(df.tail())

# ---------------------------------------------------------
# CELL 5: DISPLAY COLUMN NAMES
# ---------------------------------------------------------

# Print all column names with their serial numbers

print("Columns in the Dataset:\n")

for number, column in enumerate(df.columns, 1):
    print(number, ".", column)

# ---------------------------------------------------------
# CELL 6: DATASET INFORMATION
# ---------------------------------------------------------

# Display information about:
# - Number of records
# - Column names
# - Data types
# - Non-null values

print("Dataset Information:\n")

df.info()

# ---------------------------------------------------------
# CELL 7: CHECK FOR MISSING VALUES
# ---------------------------------------------------------

# Count missing values in every column
missing_values = df.isnull().sum()

# Display only columns that contain missing values
print("Columns containing missing values:")

display(
    missing_values[missing_values > 0]
)

# ---------------------------------------------------------
# CELL 8: CHECK FOR DUPLICATE RECORDS
# ---------------------------------------------------------

# Count the number of completely duplicated rows
duplicate_count = df.duplicated().sum()

print("Number of duplicate records:", duplicate_count)

# ---------------------------------------------------------
# CELL 9: DATA CLEANING
# ---------------------------------------------------------

# Create a copy so that the original dataset remains unchanged
df_clean = df.copy()

# ---------------------------------------------------------
# HANDLE NUMERICAL MISSING VALUES
# ---------------------------------------------------------

# Select all numerical columns
numeric_columns = df_clean.select_dtypes(
    include=np.number
).columns

# Replace missing numerical values with the median
# Median is useful because it is less affected by extreme values
for column in numeric_columns:

    df_clean[column] = df_clean[column].fillna(
        df_clean[column].median()
    )


# ---------------------------------------------------------
# HANDLE CATEGORICAL MISSING VALUES
# ---------------------------------------------------------

# Select all categorical/text columns
categorical_columns = df_clean.select_dtypes(
    include="object"
).columns

# Replace missing categorical values with the most common value
for column in categorical_columns:

    if df_clean[column].isnull().sum() > 0:

        df_clean[column] = df_clean[column].fillna(
            df_clean[column].mode()[0]
        )


# ---------------------------------------------------------
# CHECK CLEANED DATASET
# ---------------------------------------------------------

print("Data cleaning completed successfully!")

print(
    "Remaining missing values:",
    df_clean.isnull().sum().sum()
)

# ---------------------------------------------------------
# CELL 10: DESCRIPTIVE STATISTICS
# ---------------------------------------------------------

# Generate statistical summary for numerical columns
# This includes:
# count, mean, standard deviation,
# minimum, maximum and quartiles

statistics = df_clean.describe()

# Display the statistical summary
display(statistics)

# ---------------------------------------------------------
# CELL 11: NUMBER OF RECORDS BY SEASON
# ---------------------------------------------------------

# Count the number of records belonging to each season
